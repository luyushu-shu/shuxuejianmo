% 测试串联系统函数
disp('--- 串联系统测试 ---');
R1 = series(3, 0.1);             % 所有元件故障率为0.1
disp(['series(3, 0.1) = ', num2str(R1)]);

R2 = series(3, [0.1, 0.2, 0.3]); % 各元件故障率不同
disp(['series(3, [0.1, 0.2, 0.3]) = ', num2str(R2)]);


% 测试并联系统函数
disp('--- 并联系统测试 ---');
P1 = parallel(3, 0.9);              % 故障率为0.9
disp(['parallel(3, 0.9) = ', num2str(P1)]);

P2 = parallel(3, [0.9, 0.8, 0.7]);  % 各元件故障率不同
disp(['parallel(3, [0.9, 0.8, 0.7]) = ', num2str(P2)]);


% 测试表决系统函数
disp('--- 表决系统测试 ---');
V1 = vote(3, 0.1, 1);           % 至少1个元件正常
disp(['vote(3, 0.1, 1) = ', num2str(V1)]);

V2 = vote(3, 0.1, 2);           % 至少2个元件正常
disp(['vote(3, 0.1, 2) = ', num2str(V2)]);

V3 = vote(5, 0.2, 0.6);         % 至少60%元件正常（即3个）
disp(['vote(5, 0.2, 0.6) = ', num2str(V3)]);
